def hitung_luas_persegi_panjang(panjang, lebar):
    # Menghitung luas persegi panjang
    luas = panjang * lebar
    # Mengembalikan nilai luas ke pemanggil fungsi
    return luas

# Memanggil fungsi dengan memasukkan nilai panjang dan lebar
hasil = hitung_luas_persegi_panjang(12, 5)

# Menampilkan hasil
print('Luas:', hasil)